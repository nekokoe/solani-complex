#!/usr/bin/env python3
"""make_report.py — consolidate the Figure 2 H/I/J numbers into a markdown report.

Reads data/*.tsv produced by build_groups.py / compute_pi.py / compute_fst.py and writes
FIG2HIJ-report.md next to this script.
"""
import os, csv, math
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, 'data')

PI_LV = ['solani-all', 'solani-env', 'solani-clinical',
         'falciformis-all', 'falciformis-env', 'falciformis-clinical',
         'keratoplastica-all', 'keratoplastica-env', 'keratoplastica-clinical']
FJ_LV = ['falciformis-all', 'falciformis-pop1', 'falciformis-pop2', 'falciformis-pop3',
         'solani-all', 'solani-pop1', 'solani-pop2', 'solani-pop3',
         'keratoplastica-all', 'keratoplastica-pop1', 'keratoplastica-pop2']


def rd(name):
    p = os.path.join(DATA, name)
    if not os.path.exists(p):
        return None
    return list(csv.DictReader(open(p), delimiter='\t'))


def fmt(v, n=4):
    try:
        f = float(v)
    except Exception:
        return str(v)
    if f == 0:
        return '0'
    if abs(f) < 1e-4 or abs(f) >= 1e4:
        return '%.2g' % f
    return ('%.' + str(n) + 'f') % f


def main():
    pi = rd('panelH_pi_summary.tsv')
    pi_pairs = rd('panelI_pi_pairwise.tsv')
    fst = rd('panelJ_fst_matrix_v2.tsv') or rd('panelJ_fst_matrix.tsv')
    out = []
    A = out.append

    A('# Figure 2 — panels H / I / J : results report\n')
    A('> Generated by `make_report.py`. Panels are the small square files in `panels/`.\n')

    # ---------------- groups ----------------
    A('## 0. Group definitions\n')
    g = rd('fig2_groups.tsv')
    if g:
        A('Populations come from each species\' own ADMIXTURE run (`maf5pct.recode` core SNP set),')
        A('argmax Q assignment; **F. solani K=3, F. falciformis K=3, F. keratoplastica K=2**.')
        A('Pop labels are ordered by clinical fraction (descending), tie-break by sample size.\n')
        from collections import defaultdict
        comp = defaultdict(lambda: [0, 0])
        for r in g:
            c = comp[(r['species'], r['pop'])]
            if r['source'] == 'med':
                c[0] += 1
            c[1] += 1
        A('| population | n | clinical | environmental | clinical fraction |')
        A('|---|---|---|---|---|')
        for k in sorted(comp, key=lambda x: (x[0], x[1])):
            m, n = comp[k]
            e = sum(1 for r in g if r['species'] == k[0] and r['pop'] == k[1] and r['source'] == 'env')
            A('| %s | %d | %d | %d | %.2f |' % (k[1], n, m, e, m / n))
        A('')

    # ---------------- panel H ----------------
    A('## 1. Panel H — nucleotide diversity (π)\n')
    if pi:
        A('Per-window π (10 kb windows, 5 kb step, `vcftools --window-pi`), summarised as the mean')
        A('over windows — the same convention the manuscript already uses.\n')
        A('| group | n windows | mean π | median π | SD |')
        A('|---|---|---|---|---|')
        for r in pi:
            A('| %s | %s | %s | %s | %s |' % (r['group_id'], r['n_windows'], fmt(r['mean_pi'], 5),
                                              fmt(r['median_pi'], 5), fmt(r['sd_pi'], 5)))
        A('')
        d = {r['group_id']: float(r['mean_pi']) for r in pi}
        A('Species-level (all isolates):')
        for sp in ('solani', 'falciformis', 'keratoplastica'):
            A('- %s π = %s' % (sp, fmt(d['%s-all' % sp], 5)))
        A('')
        A('Clinical vs environmental within species:')
        for sp in ('solani', 'falciformis', 'keratoplastica'):
            a, b = d['%s-clinical' % sp], d['%s-env' % sp]
            higher = 'clinical' if a > b else 'environmental'
            A('- %s: clinical %s vs environmental %s  →  **%s higher** (Δ = %+.5f)'
              % (sp, fmt(a, 5), fmt(b, 5), higher, a - b))
        A('')

    # ---------------- panel I ----------------
    A('## 2. Panel I — pairwise significance of the panel-H π distributions\n')
    if pi_pairs:
        qb = [float(r['q_block']) for r in pi_pairs]
        qm = [float(r['q_mwu']) for r in pi_pairs]
        A('Two tests were computed (see `compute_pi.py`):\n')
        A('- `q_mwu` — Mann–Whitney U on all ~9,500 per-window π values. Because windows are')
        A('  spatially autocorrelated this is anticonservative: **%d/36** pairs significant,'
          % sum(1 for q in qm if q < 0.05))
        A('  median −log₁₀(q) = %.0f.' % np.median(-np.log10(np.clip(qm, 1e-300, None))))
        A('- `q_block` — **block-wise permutation** (blocks ≈ 1 Mb, 100,000 permutations, BH-FDR).')
        A('  This is the measure plotted: **%d/36** pairs significant, median −log₁₀(q) = %.1f.'
          % (sum(1 for q in qb if q < 0.05), np.median(-np.log10(np.clip(qb, 1e-300, None)))))
        A('')
        ns = [r for r in pi_pairs if r['sig_block'] == 'no']
        A('Non-significant pairs (%d):\n' % len(ns))
        A('| group A | group B | Δπ | q |')
        A('|---|---|---|---|')
        for r in ns:
            A('| %s | %s | %+.5f | %s |' % (r['group_a'], r['group_b'], float(r['delta_pi']), fmt(r['q_block'])))
        A('')
        key = [r for r in pi_pairs if {r['group_a'], r['group_b']} in
               ({'falciformis-clinical', 'falciformis-env'}, {'solani-clinical', 'solani-env'},
                {'keratoplastica-clinical', 'keratoplastica-env'})]
        A('Within-species clinical vs environmental:\n')
        A('| species | Δπ (clinical − env) | q | significant |')
        A('|---|---|---|---|')
        for r in key:
            sp = r['group_a'].split('-')[0]
            A('| %s | %+.5f | %s | %s |' % (sp, float(r['delta_pi']), fmt(r['q_block']),
                                            'yes' if r['sig_block'] == 'yes' else 'no'))
        A('')

    # ---------------- population-level pi ----------------
    poppi = rd('panelJ_pop_pi.tsv')
    A('## 2b. Nucleotide diversity of each population (resolves the §5 issue)\n')
    if poppi:
        A('Computed from the PLINK bed on the same convention as panel H (per-site π summed')
        A('over the 10-kb window and divided by the window length), then averaged over windows;')
        A('validated against the vcftools panel-H values (`solani-all` %s vs 0.00371, '
          % fmt(next((r['mean_pi'] for r in poppi if r['group'] == 'solani-all'), 0), 5))
        A('`falciformis-all` %s vs 0.00713, `keratoplastica-all` %s vs 0.00471).\n'
          % (fmt(next((r['mean_pi'] for r in poppi if r['group'] == 'falciformis-all'), 0), 5),
             fmt(next((r['mean_pi'] for r in poppi if r['group'] == 'keratoplastica-all'), 0), 5)))
        A('| group | n | mean π | median π |')
        A('|---|---|---|---|')
        for r in poppi:
            A('| %s | %s | %s | %s |' % (r['group'], r['n_samples'], fmt(r['mean_pi'], 5), fmt(r['median_pi'], 5)))
        A('')

    # ---------------- panel J ----------------
    A('## 3. Panel J — Weir & Cockerham FST between the 11 groups\n')
    if not fst:
        A('_not computed yet — run `compute_fst.py` then re-run `make_report.py`_\n')
    else:
        A('Estimator: per-site WC84 (validated against the existing vcftools file: 0.278573 vs')
        A('0.278579 for F. falciformis clinical vs environmental), summarised as the mean over')
        A('10-kb windows of the per-window mean per-site FST.\n')
        A('SNP set: species `maf5pct.recode` bed for within-species pairs, whole-complex bed')
        A('(211 isolates) for cross-species pairs.\n')
        A('Significance: 1,000 individual-level permutations. Disjoint pairs resample the A/B')
        A('membership within A ∪ B; nested `all` vs `pop` pairs hold `all` fixed and resample the')
        A('population as a random subset of the same size (this is what tests whether the')
        A('population is more distinct than a random subset of the species would be).\n')
        d = {}
        for r in fst:
            d[(r['group_a'], r['group_b'])] = r
            d[(r['group_b'], r['group_a'])] = r
        A('FST matrix (upper value = FST; `*` = permutation P < 0.05):\n')
        hdr = '| |' + '|'.join(x.replace('-', ' ') for x in FJ_LV) + '|'
        A(hdr)
        A('|---|' + '---|' * len(FJ_LV))
        for a in FJ_LV:
            cells = []
            for b in FJ_LV:
                if a == b:
                    cells.append('—')
                else:
                    r = d.get((a, b))
                    cells.append('—' if r is None else '%s%s' % (fmt(r['fst'], 3), '*' if float(r['p_perm']) < 0.05 else ''))
            A('| %s |' % a.replace('-', ' ') + '|'.join(cells) + '|')
        A('')
        ns = [r for r in fst if float(r['p_perm']) >= 0.05]
        if not ns:
            A('**All %d pairs are significant**, so a red/grey key alone would be a flat panel: every'
              % len(fst))
            A('pair sits on the 1,000-permutation floor (P = 0.001) and the colour would be uniform.')
            A('Panel J therefore encodes the *strength* of significance as the red gradient, using the')
            A('standardised position of the observed FST in its own permutation null,')
            if 'z' in fst[0]:
                zs = [float(r['z']) for r in fst if r.get('z') not in (None, '', 'nan')]
                if zs:
                    A('`z = (FST_obs - mean(null)) / sd(null)`, which is continuous and not capped by')
                    A('the number of permutations. Observed range: **z = %.1f to %.1f**.\n'
                      % (min(zs), max(zs)))
            else:
                A('(z was not recorded in this run; the panel colours by FST magnitude instead).\n')
            A('Dot size encodes FST magnitude (0.03-0.85; cross-species 0.49-0.85 vs within-species')
            A('0.03-0.57), so the three species blocks read immediately.\n')
        A('Non-significant pairs (%d of %d):\n' % (len(ns), len(fst)))
        if ns:
            A('| group A | group B | FST | P |')
            A('|---|---|---|---|')
            for r in ns:
                A('| %s | %s | %s | %s |' % (r['group_a'], r['group_b'], fmt(r['fst'], 4), fmt(r['p_perm'], 3)))
        A('')
        A('Within-species population structure (FST among populations, all significant unless noted):\n')
        for sp, pops in (('falciformis', 3), ('solani', 3), ('keratoplastica', 2)):
            gs = ['%s-pop%d' % (sp, i) for i in range(1, pops + 1)]
            for i in range(len(gs)):
                for j in range(i + 1, len(gs)):
                    r = d.get((gs[i], gs[j]))
                    if r:
                        A('- %s vs %s: FST = %s (P = %s)' % (gs[i], gs[j], fmt(r['fst'], 4), fmt(r['p_perm'], 3)))
        A('')
        A('Differentiation of each population from its own species as a whole (nested):\n')
        for sp, pops in (('falciformis', 3), ('solani', 3), ('keratoplastica', 2)):
            for i in range(1, pops + 1):
                r = d.get(('%s-all' % sp, '%s-pop%d' % (sp, i)))
                if r:
                    A('- %s vs %s: FST = %s (P = %s)' % ('%s-all' % sp, '%s-pop%d' % (sp, i),
                                                         fmt(r['fst'], 4), fmt(r['p_perm'], 3)))
        A('')
        A('Species-level (all vs all):\n')
        for a in range(len(FJ_LV)):
            for b in range(a + 1, len(FJ_LV)):
                if FJ_LV[a].endswith('-all') and FJ_LV[b].endswith('-all'):
                    r = d[(FJ_LV[a], FJ_LV[b])]
                    A('- %s vs %s: FST = %s (P = %s)' % (FJ_LV[a], FJ_LV[b], fmt(r['fst'], 4), fmt(r['p_perm'], 3)))
        A('')

    # ---------------- manuscript impact ----------------
    A('## 4. Consequences for the manuscript text\n')
    A('The following sentences contain numbers that the recomputation changes:\n')
    A('| manuscript claim | current text | recomputed | action |')
    A('|---|---|---|---|')
    if pi:
        d = {r['group_id']: float(r['mean_pi']) for r in pi}
        A('| species π (Fig. 2H) | falciformis 0.0071, keratoplastica 0.0047, solani 0.0037 | '
          'falciformis %s, keratoplastica %s, solani %s | unchanged |'
          % (fmt(d['falciformis-all'], 5), fmt(d['keratoplastica-all'], 5), fmt(d['solani-all'], 5)))
        A('| solani clinical vs env π | 0.0036 vs 0.0038, P = 0.68 | %s vs %s; block-permutation q = %s | update P |'
          % (fmt(d['solani-clinical'], 5), fmt(d['solani-env'], 5),
             next((fmt(r['q_block']) for r in (pi_pairs or []) if {r['group_a'], r['group_b']} ==
                   {'solani-clinical', 'solani-env'}), 'n/a')))
        A('| keratoplastica clinical vs env π | 0.0046 vs 0.0051, P = 0.53 | %s vs %s; block-permutation q = %s | update both numbers |'
          % (fmt(d['keratoplastica-clinical'], 5), fmt(d['keratoplastica-env'], 5),
             next((fmt(r['q_block']) for r in (pi_pairs or []) if {r['group_a'], r['group_b']} ==
                   {'keratoplastica-clinical', 'keratoplastica-env'}), 'n/a')))
        A('| falciformis clinical π "markedly reduced" | clinical reduced relative to non-clinical | '
          'clinical %s **>** environmental %s (Δ = %+.5f), q = %s | **direction is wrong — see §5** |'
          % (fmt(d['falciformis-clinical'], 5), fmt(d['falciformis-env'], 5),
             d['falciformis-clinical'] - d['falciformis-env'],
             next((fmt(r['q_block']) for r in (pi_pairs or []) if {r['group_a'], r['group_b']} ==
                   {'falciformis-clinical', 'falciformis-env'}), 'n/a')))
        A('| keratoplastica environmental isolates "only three" | three | '
          'the cohort holds **4** environmental isolates (19 clinical + 4) | check wording |')
    A('')
    A('## 5. ⚠️ F. falciformis π "markedly reduced" — how the discrepancy resolves\n')
    A('The text states that *"clinical isolates of F. falciformis had markedly reduced nucleotide')
    A('diversity relative to non-clinical isolates within the same species"*. Pooled by isolation')
    A('source the data say the opposite (clinical %s vs environmental %s; block-permutation'
      % (fmt(next((r['mean_pi'] for r in (pi or []) if r['group_id'] == 'falciformis-clinical'), 0), 5),
         fmt(next((r['mean_pi'] for r in (pi or []) if r['group_id'] == 'falciformis-env'), 0), 5)))
    A('q = %s). Group membership was verified independently (48 clinical / 18 environmental matches'
      % next((fmt(r['q_block']) for r in (pi_pairs or []) if {r['group_a'], r['group_b']} ==
              {'falciformis-clinical', 'falciformis-env'}), 'n/a'))
    A('the original vcftools logs exactly) and π was recomputed straight from genotypes, so this is')
    A('not a labelling artefact.\n')
    A('**At the population level the original intuition is correct.** The three F. falciformis')
    A('populations differ sharply in diversity:')
    if poppi:
        for r in poppi:
            if r['group'].startswith('falciformis-pop'):
                A('- %s (n=%s): π = %s' % (r['group'], r['n_samples'], fmt(r['mean_pi'], 5)))
    A('')
    A('Population 1 — the fully clinical, n=10 lineage — is by far the most homogeneous (π ≈ 0.0019),')
    A('a factor ~2 below the environmental-dominated population 3 (π ≈ 0.0041). Pooling by source')
    A('inverts the comparison because the clinical stratum pools the very homogeneous population 1')
    A('with the more diverse population 2: variance *between* populations inflates the pooled π of')
    A('the clinical group. This is a pooling artefact, not a contradiction.\n')
    A('Options for the text:')
    A('1. Report it at the population level — "the clinical-dominated population 1 of F. falciformis')
    A('   is markedly more homogeneous (π = 0.0019) than the environmental population 3 (π = 0.0041)".')
    A('   This is supported by the data and keeps the intended message.')
    A('2. Keep the source-stratified comparison but reverse the direction and state the pooled values.')
    A('3. Drop the sentence entirely and let panel H speak for itself.\n')
    A('Whatever is chosen, the caption for panel H must state whether the groups are source strata')
    A('or populations, because the two give opposite answers for F. falciformis.\n')

    open(os.path.join(HERE, 'FIG2HIJ-report.md'), 'w').write('\n'.join(out) + '\n')
    print('wrote FIG2HIJ-report.md')


if __name__ == '__main__':
    main()
